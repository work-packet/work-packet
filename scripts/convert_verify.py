"""Check a real ``wpk convert`` (docs/run-binding-v1.md R9): the project's
dashboard pages and statistics are the same before and after.

    python scripts/convert_verify.py before NAME
    wpk convert NAME
    python scripts/convert_verify.py after NAME

``before`` saves a page crawl and the stats report under
``~/.work-packet/migration/convert/``; ``after`` crawls again and writes
``NAME-verify.md`` there with any differences. Reads only (GET requests).
"""

import os
import pickle
import sys

REAL = os.path.expanduser(os.environ.get("WPK_HOME") or "~/.work-packet")
OUT = os.path.join(REAL, "migration", "convert")


def _crawl(name):
    from starlette.testclient import TestClient
    from work_packet.dash import crawl
    from work_packet.dash.app import create_app
    return crawl.crawl(TestClient(create_app()), name)


def _stats(name):
    from work_packet import registry, stats
    e = registry.get(name)
    return e["path"], stats.report(stats.groups(*stats.collect([(name, e["path"])])))


def _tokens(pages, subst):
    out = {}
    for u, (st, body) in pages.items():
        for x, y in subst:
            body = body.replace(x, y) if isinstance(body, str) else \
                body.replace(x.encode(), y.encode())
        out[u] = (st, body)
    return out


def main(phase, name):
    from work_packet import layout
    os.makedirs(OUT, exist_ok=True)
    keep = os.path.join(OUT, "%s-before.pickle" % name)
    if phase == "before":
        path, st = _stats(name)
        pages = _crawl(name)
        with open(keep, "wb") as fp:
            pickle.dump({"path": path, "stats": st, "pages": pages}, fp)
        print("%d pages, stats saved: %s" % (len(pages), keep))
        return 0
    from work_packet.dash import crawl
    with open(keep, "rb") as fp:
        b = pickle.load(fp)
    old = b["path"]
    path, st = _stats(name)
    folder = layout.packet_folder(path)
    before = _tokens(b["pages"], [(layout.runs_dir(old), "@RUNS@"), (old, "@PROJ@")])
    after = _tokens(_crawl(name), [(layout.runs_dir(path), "@RUNS@"), (path, "@PROJ@"),
                                   (layout.runs_dir(old), "@RUNS@"), (old, "@PROJ@"),
                                   (folder, "@PROJ@")])
    probs = crawl.compare(before, after)
    md = ["# wpk convert %s: verification" % name, "",
          "Generated by `scripts/convert_verify.py`.", "",
          "- from `%s`" % old, "- to `%s`" % path,
          "- stats: %s" % ("identical" if st == b["stats"] else "**differ**"),
          "- pages: %d before, %d after, %d differ" % (len(before), len(after), len(probs)), ""]
    md += ["- %s" % p for p in probs]
    out = os.path.join(OUT, "%s-verify.md" % name)
    with open(out, "w") as fp:
        fp.write("\n".join(md) + "\n")
    print("\n".join(md[6:9]))
    print(out)
    return 0 if st == b["stats"] and not probs else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1], sys.argv[2]))
